<?php

declare(strict_types=1);

namespace Tey\Standards\Enforcement;

use InvalidArgumentException;
use Symfony\Component\Process\Process;
use Tey\Standards\Patterns\Branch;
use Tey\Standards\Patterns\Leaf;
use Tey\Standards\Patterns\Lookup;
use Tey\Standards\Patterns\PatternCatalog;
use Tey\Standards\Patterns\TreeCatalog;

/**
 * Writes the agent guardrails into an app: a generated pattern index between
 * markers in AGENTS.md, one Boost skill per recipe, path-scoped Claude skills,
 * merged .claude/settings.json hooks and a pre-push hook. Re-running refreshes
 * what it owns and leaves everything else alone.
 */
final class Installer
{
    public const START = '<!-- tey/standards:patterns:start -->';

    public const END = '<!-- tey/standards:patterns:end -->';

    /** The one always-loaded line, in AGENTS.md and the Boost guideline. */
    public const GUIDE = 'Before implementing a page, action, MCP tool, setting, notification, job or integration, call bakery.find (offline: `php artisan standards:pattern "<intent or path>"`).';

    public const HOOK_MARKER = 'tey/standards/bin/standards hook';

    private const PRE_PUSH_MARKER = '# tey/standards pre-push';

    public function __construct(private readonly string $base, private readonly PatternCatalog $catalog) {}

    /** @return list<string> one line per file written or left alone */
    public function install(): array
    {
        return [
            ...$this->configuration(),
            $this->agents(),
            ...$this->skills(),
            $this->settings(),
            $this->boost(),
            $this->prePush(),
        ];
    }

    /**
     * Scaffolds tests/Arch/configuration.php (a Configuration inferred from
     * composer.json and the app's folders) and a ConformanceTest that
     * requires it, so standards:check can run. Never overwrites either.
     *
     * @return list<string>
     */
    public function configuration(): array
    {
        $file = $this->base.'/tests/Arch/configuration.php';
        $lines = [];

        if (is_file($file)) {
            $lines[] = 'tests/Arch/configuration.php kept';
        } else {
            [$arguments, $notes] = $this->infer();

            if (! is_dir(dirname($file))) {
                mkdir(dirname($file), 0777, true);
            }

            $body = '';

            foreach ($arguments as $name => $value) {
                $body .= '    '.$name.': '.($name === 'base' ? 'dirname(__DIR__, 2)' : self::export($value)).",\n";
            }

            file_put_contents($file, "<?php\n\ndeclare(strict_types=1);\n\nuse Tey\\Standards\\Configuration;\n\n// Generated by php artisan standards:install from this app's composer.json and folders.\n// Review and adjust it: it is yours now, and standards:install never overwrites it.\n// See vendor/tey/standards/src/Configuration.php for every option.\nreturn new Configuration(\n".$body.");\n");
            $lines[] = 'tests/Arch/configuration.php scaffolded; inferred: '.implode('; ', $notes);
        }

        $test = $this->base.'/tests/Arch/ConformanceTest.php';

        if (is_file($test) || $this->hasConformanceTest()) {
            $lines[] = 'Arch conformance test kept';
        } else {
            file_put_contents($test, <<<'PHP'
                <?php

                declare(strict_types=1);

                use Tey\Standards\Conformance;

                // Generated by php artisan standards:install. Add tests/Arch to phpunit.xml to run it.
                foreach (Conformance::TESTS as $rule => $name) {
                    arch($name, function () use ($rule): void {
                        static $preset;
                        $preset ??= new Conformance(require __DIR__.'/configuration.php');
                        $preset->assert((string) $rule);
                    });
                }

                PHP);
            $lines[] = 'tests/Arch/ConformanceTest.php scaffolded';
        }

        return $lines;
    }

    /** @return array{0: array<string, mixed>, 1: list<string>} constructor arguments and what was inferred */
    private function infer(): array
    {
        $composer = json_decode((string) @file_get_contents($this->base.'/composer.json'), true);
        $composer = is_array($composer) ? $composer : [];
        $packages = [...array_keys($composer['require'] ?? []), ...array_keys($composer['require-dev'] ?? [])];
        $classRoots = [];

        foreach ($composer['autoload']['psr-4'] ?? [] as $namespace => $directories) {
            foreach ((array) $directories as $directory) {
                $directory = trim(str_replace('\\', '/', (string) $directory), '/');

                if ($directory !== '' && is_dir($this->base.'/'.$directory)) {
                    $classRoots[$directory] = rtrim((string) $namespace, '\\');
                }
            }
        }

        if ($classRoots === [] && is_dir($this->base.'/app')) {
            $classRoots = ['app' => 'App'];
        }

        $roots = array_keys($classRoots);
        $namespaces = array_values(array_unique(array_values($classRoots)));
        $main = $roots[0] ?? 'app';
        $mainNamespace = $classRoots[$main] ?? 'App';
        $pages = [];

        // Case-insensitive filesystems report both spellings for one folder; keep the first.
        foreach (['resources/js/pages', 'resources/js/Pages'] as $path) {
            $inode = is_dir($this->base.'/'.$path) ? fileinode($this->base.'/'.$path) : false;

            if ($inode !== false && ! in_array($inode, array_column($pages, 1), true)) {
                $pages[] = [$path, $inode];
            }
        }

        $pages = array_column($pages, 0);
        $kit = in_array('tey/kit', $packages, true) || is_dir($this->base.'/vendor/tey/kit');
        $mod = in_array('tey/mod', $packages, true) || is_dir($this->base.'/vendor/tey/mod');
        $typed = $this->typedViewModel($kit, $packages);
        [$layout, $modControllers, $modViewModels, $modPages] = $this->modLayout($mod);
        $globs = fn (string $suffix): array => array_values(array_unique([...array_map(fn (string $root): string => $root.'/'.$suffix, $roots), ...array_map(fn (string $root): string => $root.'/*/'.$suffix, $roots)]));

        $arguments = [
            'base' => null,
            'classRoots' => $classRoots,
            'sourceRoots' => [...$roots, ...(is_dir($this->base.'/routes') ? ['routes'] : [])],
            'uiRoots' => [$main.'/UI*'],
            'uiNamespaces' => [$mainNamespace.'\\UI'],
            'hostNamespaces' => $namespaces,
            'controllerRoots' => array_values(array_unique([...$globs('Http/Controllers*'), ...$modControllers])),
            'routeRoots' => is_dir($this->base.'/routes') ? ['routes'] : [],
            'controllerSuffix' => 'Controller',
            'routeDirectory' => 'routes',
            'viewModelRoots' => array_values(array_unique([...$globs('ViewModels*'), ...$modViewModels])),
            'viewModelBases' => $typed === '' ? [] : [$typed],
            'typedViewModel' => $typed,
            'viewModelSuffix' => 'ViewModel',
            'pageRoots' => [...($pages === [] ? ['resources/js/pages*'] : $pages), ...$modPages],
            'pageScaffolds' => array_values(array_unique([...['resources', 'js', 'pages', 'Pages', 'layouts', 'components', 'auth', 'settings', 'app'], ...\Tey\Standards\PageConventions::scaffolds($this->base)])),
            'placements' => [],
            'retired' => [],
            'discoveryRoots' => $roots,
            'developmentNamespaces' => ['Pest', 'PHPUnit', 'Mockery', 'Faker', 'Laravel\\Dusk'],
            'safeAttributes' => [],
            'mediaTrait' => 'Spatie\\MediaLibrary\\InteractsWithMedia',
            'mediaInterface' => 'Spatie\\MediaLibrary\\HasMedia',
        ];

        $notes = [
            'class roots '.($classRoots === [] ? 'none found' : implode(', ', array_map(fn (string $root, string $namespace): string => "{$root} => {$namespace}", $roots, array_values($classRoots)))),
            'Inertia pages '.($pages === [] ? 'not found (glob resources/js/pages*)' : implode(', ', $pages)),
            'typed ViewModel base '.($typed === '' ? 'none found (ViewModels are checked by suffix; set typedViewModel once the app has a base)' : $typed),
            'tey/kit '.($kit ? 'present' : 'absent'),
            'tey/mod '.($mod ? 'present, layout '.$layout.($modControllers === [] ? '' : ', module controllers '.implode(', ', $modControllers)) : 'absent'),
            'optional UI rules off (enable in optionalRules)',
        ];

        return [$arguments, $notes];
    }

    /**
     * Module-aware roots for a tey/mod app: the layout named in config/mod.php
     * decides where module controllers, ViewModels and pages live, and any
     * controller found under a module folder outside them is generalised over
     * its module name, so module controllers are never reported as misplaced.
     *
     * @return array{0: string, 1: list<string>, 2: list<string>, 3: list<string>} layout, controller, ViewModel and page roots
     */
    private function modLayout(bool $mod): array
    {
        if (! $mod) {
            return ['none', [], [], []];
        }

        $config = is_file($this->base.'/config/mod.php') ? (string) file_get_contents($this->base.'/config/mod.php') : '';
        $layout = preg_match("/'layout'\s*=>\s*'([\w-]+)'/", $config, $match) === 1 ? $match[1] : 'laravel';
        $bases = match ($layout) {
            'modules', 'ddd' => ['app/Modules/*'],
            'features' => ['app/Features/*'],
            'slices' => ['app/*'],
            'type-first' => ['app/*/*'],
            default => [],
        };
        $controllers = $layout === 'ddd'
            ? ['app/Modules/*/Controllers', 'app/Modules/*/*/Controllers']
            : array_map(fn (string $base): string => $base.'/Http/Controllers*', $bases);
        $viewModels = array_map(fn (string $base): string => $base.'/ViewModels*', $bases);
        $pages = array_values(array_filter(array_map(fn (string $base): string => $base.'/resources/js/pages', $bases), fn (string $glob): bool => (glob($this->base.'/'.$glob, GLOB_ONLYDIR) ?: []) !== []));

        foreach (['app/Modules', 'app/Features', 'app/Domains', 'src/Domain'] as $parent) {
            foreach (glob($this->base.'/'.$parent.'/*', GLOB_ONLYDIR) ?: [] as $module) {
                foreach (new \RecursiveIteratorIterator(new \RecursiveDirectoryIterator($module, \FilesystemIterator::SKIP_DOTS)) as $file) {
                    if (! str_ends_with($file->getFilename(), 'Controller.php')) {
                        continue;
                    }

                    $directory = str_replace('\\', '/', substr(dirname($file->getPathname()), strlen($this->base) + 1));
                    $generalised = $parent.'/*'.substr($directory, strlen($parent) + 1 + strlen(basename($module)));
                    $covered = false;

                    foreach ($controllers as $root) {
                        $covered = $covered || fnmatch(rtrim($root, '*').'*', $directory) || fnmatch($root, $directory);
                    }

                    if (! $covered) {
                        $controllers[] = $generalised;
                    }
                }
            }
        }

        return [$layout, array_values(array_unique($controllers)), $viewModels, $pages];
    }

    /** @param list<string> $packages */
    private function typedViewModel(bool $kit, array $packages): string
    {
        if ($kit) {
            return 'Tey\\Kit\\Features\\Core\\ViewModels\\ViewModel';
        }

        foreach (['app/ViewModels/ViewModel.php', 'app/UI/ViewModel.php', 'app/Support/ViewModel.php'] as $candidate) {
            if (is_file($this->base.'/'.$candidate) && preg_match('/namespace\s+([^;]+);/', (string) file_get_contents($this->base.'/'.$candidate), $match) === 1) {
                return $match[1].'\\ViewModel';
            }
        }

        // No typed base to infer: none, rather than a class the app does not have (rule 20 then checks ViewModels by suffix only).
        return in_array('spatie/laravel-data', $packages, true) ? 'Spatie\\LaravelData\\Data' : '';
    }

    private function hasConformanceTest(): bool
    {
        if (! is_dir($this->base.'/tests')) {
            return false;
        }

        foreach (new \RecursiveIteratorIterator(new \RecursiveDirectoryIterator($this->base.'/tests', \FilesystemIterator::SKIP_DOTS)) as $file) {
            if (str_ends_with($file->getFilename(), '.php') && str_contains((string) file_get_contents($file->getPathname()), 'Conformance::TESTS')) {
                return true;
            }
        }

        return false;
    }

    private static function export(mixed $value): string
    {
        if (! is_array($value)) {
            return var_export($value, true);
        }

        if ($value === []) {
            return '[]';
        }

        $items = array_is_list($value)
            ? array_map(fn (mixed $item): string => self::export($item), $value)
            : array_map(fn (string|int $key, mixed $item): string => var_export($key, true).' => '.self::export($item), array_keys($value), $value);

        return '['.implode(', ', $items).']';
    }

    public function agents(): string
    {
        $file = $this->base.'/AGENTS.md';
        $block = self::START."\n".$this->index().self::END;
        $current = is_file($file) ? (string) file_get_contents($file) : "# Agent guidance\n";
        $start = strpos($current, self::START);
        $end = strpos($current, self::END);

        if ($start !== false && $end !== false && $end > $start) {
            $updated = substr($current, 0, $start).$block.substr($current, $end + strlen(self::END));
        } elseif ($start === false && $end === false) {
            $updated = rtrim($current)."\n\n".$block."\n";
        } else {
            throw new InvalidArgumentException('AGENTS.md has an unmatched tey/standards marker; fix it by hand.');
        }

        file_put_contents($file, $updated);

        return 'AGENTS.md pattern index refreshed';
    }

    public function index(): string
    {
        $lines = [
            '## Patterns (generated by `php artisan standards:install`; do not edit)',
            '',
            self::GUIDE,
            '',
            '**Traverse before you build.** Answer the questions until you reach a leaf (or a feature plan), then scaffold with its make command. Stamp hand-written new files with `// '.Hook::STAMP.' <leaf-id>`, or `gap` when no leaf fits. Never hand-roll a kit primitive. Name the pattern in the commit. `php artisan standards:check --changed` must pass before commit and push.',
            '',
            '| Leaf | Status | Building… | Make | Checks |',
            '| ---- | ------ | --------- | ---- | ------ |',
        ];

        foreach ($this->catalog->leaves() as $leaf) {
            if ($leaf->status === 'byo') {
                continue;
            }

            $lines[] = '| `'.$leaf->id.'` | '.$leaf->status.' | '.str_replace('|', '\\|', $leaf->summary).' | '.($leaf->make === null ? '—' : '`php artisan '.$leaf->make.' <Name>`').($leaf->recipeMake === null ? '' : ' (Bakery: `php artisan '.str_replace('{Name}', '<Name>', $leaf->recipeMake).'`)').' | '.implode(', ', $leaf->checks).' |';
        }

        return implode("\n", $lines)."\n";
    }

    /** @return list<string> */
    public function skills(): array
    {
        $written = [];

        foreach ($this->catalog->leaves() as $leaf) {
            if (in_array($leaf->status, ['gap', 'byo'], true)) {
                continue;
            }

            $name = 'standards-'.str_replace('.', '-', $leaf->id);
            $body = $this->skill($leaf, $name);

            foreach (['.ai/skills', '.claude/skills'] as $root) {
                $directory = $this->base.'/'.$root.'/'.$name;

                if (! is_dir($directory)) {
                    mkdir($directory, 0777, true);
                }

                file_put_contents($directory.'/SKILL.md', $body);
            }

            $written[] = $name.' skill written';
        }

        return $written;
    }

    private function skill(Leaf $leaf, string $name): string
    {
        $front = ['---', 'name: '.$name, 'description: '.json_encode('Use when building '.lcfirst($leaf->recipe).': '.$leaf->summary, JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE)];

        if ($leaf->paths !== []) {
            $front[] = 'paths:';

            foreach ($leaf->paths as $path) {
                $front[] = '  - '.json_encode($path, JSON_UNESCAPED_SLASHES);
            }
        }

        $parent = $this->catalog->parentOf($leaf->id);

        return implode("\n", [
            ...$front,
            '---',
            '',
            '# '.$leaf->recipe,
            '',
            '<!-- Generated by php artisan standards:install from tey/standards; do not edit. -->',
            '',
            $leaf->summary,
            '',
            $leaf->make === null ? 'No generator yet; follow the summary and stamp the file `'.Hook::STAMP.' '.$leaf->id.'`.' : 'Scaffold: `php artisan '.$leaf->make.' <Name>`.'.($leaf->recipeMake === null ? '' : ' With the Bakery ('.Lookup::RECIPE_PACKAGE.') installed, prefer `php artisan '.str_replace('{Name}', '<Name>', $leaf->recipeMake).'`.'),
            '',
            'Kit: '.($leaf->kit === [] ? 'none' : implode(', ', $leaf->kit)).'.',
            ...array_map(fn (array $c): string => "- `{$c['kit_component']}` from `@kit/ui` for the {$c['name']}: {$c['use']} (props: {$c['props_hint']}).", $leaf->components),
            'Checks: '.($leaf->checks === [] ? 'none' : implode(', ', $leaf->checks)).'. Run `php artisan standards:check --changed` before committing.',
            $parent instanceof Branch ? "\nNot sure this is the right leaf? It answers \"{$parent->question}\" Call bakery.find, or run `php artisan standards:pattern --recipe={$leaf->id}` to see its siblings." : '',
            '',
        ]);
    }

    public function settings(): string
    {
        $file = $this->base.'/.claude/settings.json';
        $settings = [];

        if (is_file($file)) {
            $settings = json_decode((string) file_get_contents($file), true);

            if (! is_array($settings)) {
                throw new InvalidArgumentException('.claude/settings.json is not a JSON object; refusing to overwrite it.');
            }
        }

        $hooks = is_array($settings['hooks'] ?? null) ? $settings['hooks'] : [];
        $ours = [
            'Stop' => [[null, 'stop']],
            'PreToolUse' => [['Bash', 'pre-commit'], ['Write', 'pre-write']],
            'PostToolUse' => [['Edit|MultiEdit|Write', 'post-edit']],
        ];

        foreach ($hooks as $event => $groups) {
            $hooks[$event] = array_values(array_filter(array_map(function (array $group): ?array {
                $group['hooks'] = array_values(array_filter($group['hooks'] ?? [], fn (array $hook): bool => ! str_contains((string) ($hook['command'] ?? ''), self::HOOK_MARKER)));

                return $group['hooks'] === [] ? null : $group;
            }, is_array($groups) ? $groups : [])));
        }

        foreach ($ours as $event => $entries) {
            foreach ($entries as [$matcher, $name]) {
                $group = ['hooks' => [['type' => 'command', 'command' => self::command($name), 'timeout' => 300]]];

                if ($matcher !== null) {
                    $group = ['matcher' => $matcher, ...$group];
                }

                $hooks[$event][] = $group;
            }
        }

        $settings['hooks'] = array_filter($hooks, fn (array $groups): bool => $groups !== []);

        if (! is_dir(dirname($file))) {
            mkdir(dirname($file), 0777, true);
        }

        file_put_contents($file, json_encode($settings, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_THROW_ON_ERROR)."\n");

        return '.claude/settings.json hooks merged';
    }

    /**
     * Boost 2.10's boost:update refuses to run without `agents`, and boost:install
     * without `packages` deletes the project's third-party skills. Fill in
     * whichever is missing, inferred from the app, and never change one that is set.
     */
    public function boost(): string
    {
        $composer = json_decode(is_file($this->base.'/composer.json') ? (string) file_get_contents($this->base.'/composer.json') : '', true);

        if (! is_array($composer) || ! isset($composer['require-dev']['laravel/boost']) && ! isset($composer['require']['laravel/boost'])) {
            return 'boost.json skipped: laravel/boost is not required';
        }

        $file = $this->base.'/boost.json';
        $config = is_file($file) ? json_decode((string) file_get_contents($file), true) : [];

        if (! is_array($config) || ($config !== [] && array_is_list($config))) {
            return 'boost.json left alone: it is not a JSON object; fix it, then add "agents" and "packages"';
        }

        $added = [];

        if (! is_array($config['agents'] ?? null) || $config['agents'] === []) {
            $agents = array_keys(array_filter(['claude_code' => true, 'codex' => is_dir($this->base.'/.codex') || is_dir($this->base.'/.agents')]));
            $config['agents'] = $agents;
            $added[] = 'agents ('.implode(', ', $agents).')';
        }

        if (! is_array($config['packages'] ?? null)) {
            $packages = [];

            foreach (array_keys([...($composer['require'] ?? []), ...($composer['require-dev'] ?? [])]) as $package) {
                if (str_contains((string) $package, '/') && is_dir($this->base.'/vendor/'.$package.'/resources/boost')) {
                    $packages[] = (string) $package;
                }
            }

            $config['packages'] = $packages;
            $added[] = 'packages ('.($packages === [] ? 'none found' : implode(', ', $packages)).')';
        }

        if ($added === []) {
            return 'boost.json kept: agents and packages are set';
        }

        file_put_contents($file, json_encode($config, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_THROW_ON_ERROR)."\n");

        return 'boost.json: added '.implode(' and ', $added).'; review them before boost:install or boost:update';
    }

    /** The hook exits 0 before running anything when the package is not installed here. */
    public static function command(string $event): string
    {
        return 'cd "${CLAUDE_PROJECT_DIR:-.}" && { test -f vendor/tey/standards/bin/standards || exit 0; } && php vendor/tey/standards/bin/standards hook '.$event;
    }

    public function prePush(): string
    {
        $hooks = $this->gitHooks();

        if ($hooks === null) {
            return 'pre-push skipped: not a git checkout';
        }

        $hooksPath = $this->hooksPath();

        if ($hooksPath !== null) {
            $base = rtrim(str_replace('\\', '/', (string) (realpath($this->base) ?: $this->base)), '/').'/';
            $resolved = str_replace('\\', '/', $hooksPath);

            if (! str_starts_with(rtrim($resolved, '/').'/', $base)) {
                return 'pre-push not written: core.hooksPath points outside this repository ('.$hooksPath.'); add this line to its pre-push hook: [ -f vendor/tey/standards/bin/standards ] && php artisan standards:check --changed';
            }

            $hooks = $hooksPath;
        }

        $file = $hooks.'/pre-push';

        if (is_file($file) && ! str_contains((string) file_get_contents($file), self::PRE_PUSH_MARKER)) {
            return 'pre-push left alone: an existing hook is not ours; add `php artisan standards:check --changed` to it';
        }

        if (! is_dir($hooks)) {
            mkdir($hooks, 0777, true);
        }

        file_put_contents($file, implode("\n", [
            '#!/bin/sh',
            self::PRE_PUSH_MARKER,
            '[ -f vendor/tey/standards/bin/standards ] || exit 0',
            'exec php artisan standards:check --changed',
            '',
        ]));
        chmod($file, 0755);

        return 'pre-push hook installed';
    }

    /** core.hooksPath as git resolves it (relative to the work tree, ~ expanded), or null when unset. */
    private function hooksPath(): ?string
    {
        $process = new Process(['git', 'config', '--get', 'core.hooksPath'], $this->base);
        $process->run();
        $path = trim($process->getOutput());

        if (! $process->isSuccessful() || $path === '') {
            return null;
        }

        if (str_starts_with($path, '~/')) {
            $path = rtrim((string) getenv('HOME'), '/').substr($path, 1);
        } elseif (! str_starts_with($path, '/') && preg_match('/^[A-Za-z]:/', $path) !== 1) {
            $path = (realpath($this->base) ?: $this->base).'/'.$path;
        }

        $path = rtrim($path, '/');

        // Normalise ./ and ../ segments without requiring the directory to exist.
        $parts = [];

        foreach (explode('/', str_replace('\\', '/', $path)) as $i => $part) {
            if ($part === '..') {
                array_pop($parts);
            } elseif ($part !== '.' && ($part !== '' || $i === 0)) {
                $parts[] = $part;
            }
        }

        $path = implode('/', $parts);

        return realpath($path) ?: $path;
    }

    private function gitHooks(): ?string
    {
        $git = $this->base.'/.git';

        if (is_dir($git)) {
            return $git.'/hooks';
        }

        if (is_file($git) && preg_match('/^gitdir:\s*(.+)$/m', (string) file_get_contents($git), $match) === 1) {
            $directory = trim($match[1]);
            $directory = str_starts_with($directory, '/') ? $directory : $this->base.'/'.$directory;
            $common = is_file($directory.'/commondir') ? $directory.'/'.trim((string) file_get_contents($directory.'/commondir')) : $directory;

            return $common.'/hooks';
        }

        return null;
    }

    public static function shipped(string $base): self
    {
        return new self($base, TreeCatalog::shipped());
    }
}
